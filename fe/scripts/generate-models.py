#!/usr/bin/env python3
"""Generate exact, null-preserving Codable shapes from the read-only v1 contract."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
defs = json.loads((root / 'contracts/state.schema.json').read_text())['$defs']
# Explicit build-time adoption of the frozen additive Sandbox profile; base files stay read-only.
profile = json.loads((root / 'contracts/plaid.schema.json').read_text())['$defs']
for field in ['adapter', 'method']:
    defs['provenance']['properties'][field]['enum'].append(profile['sandbox_provenance']['properties'][field]['const'])
for kind in ['link_token', 'exchange', 'sync', 'disconnect']:
    for direction in ['request', 'response']:
        key = kind + '_' + direction
        defs['plaid_' + key] = json.loads(json.dumps(profile[key]).replace('state.schema.json#/', '#/'))
experience = json.loads((root / 'contracts/experience.schema.json').read_text())['$defs']
def experience_refs(value):
    if isinstance(value, dict):
        return {k: ('#/$defs/experience_' + v.split('/')[-1] if k == '$ref' and v.startswith('#/$defs/') else experience_refs(v)) for k,v in value.items()}
    if isinstance(value, list): return [experience_refs(v) for v in value]
    return value
for key, value in experience.items():
    defs['experience_' + key] = experience_refs(value)
patterns = json.loads((root / 'contracts/patterns.schema.json').read_text())['$defs']
def pattern_refs(value):
    if isinstance(value, dict):
        return {k: ('#/$defs/pattern_' + v.split('/')[-1] if k == '$ref' else pattern_refs(v)) for k,v in value.items()}
    if isinstance(value, list): return [pattern_refs(v) for v in value]
    return value
for key, value in patterns.items():
    defs['pattern_' + key] = pattern_refs(value)
notifications = json.loads((root / 'contracts/report_notifications.schema.json').read_text())['$defs']
def notification_refs(value):
    if isinstance(value, dict): return {k: ('#/$defs/notification_' + v.split('/')[-1] if k == '$ref' else notification_refs(v)) for k,v in value.items()}
    if isinstance(value, list): return [notification_refs(v) for v in value]
    return value
for key,value in notifications.items(): defs['notification_'+key]=notification_refs(value)
# Explicit additive deployment errors; frozen base artifacts are not rewritten.
for code in ['stale_experience', 'obsolete_pattern', 'unauthorized', 'session_pending', 'auth_unavailable']:
    defs['error']['properties']['error']['properties']['code']['enum'].append(code)
names = {k: ''.join(x.title() for x in k.split('_')) for k in defs}
names['error'] = 'APIErrorEnvelope'
names['notification'] = 'NotificationIntent'
names['process'] = 'ProcessingState'
names['experience_experience'] = 'ExperienceV1'
names['experience_error'] = 'ExperienceErrorEnvelope'
names['pattern_Overview'] = 'PatternOverview'
names['pattern_Request'] = 'PatternAnalyzeRequest'
names['pattern_ClarifyRequest'] = 'PatternClarifyRequest'
names['pattern_HealthRecord'] = 'NormalizedHealthSample'
names['pattern_HealthIngestRequest'] = 'HealthIngestRequest'
names['pattern_BriefRequest'] = 'PatternBriefRequest'
for name in ['WorkflowOverview','WorkflowAction','WorkflowPage','WorkflowChoice','WorkflowQuestion','WorkflowJob','EnqueueRequest']:
    names['pattern_'+name]=name
for name in notifications: names['notification_'+name]=name
objects = []
def typ(p, name):
    if 'anyOf' in p:
        return typ(next(x for x in p['anyOf'] if x.get('type') != 'null'), name) + '?'
    if '$ref' in p: return names[p['$ref'].split('/')[-1]]
    t = p.get('type')
    if t == 'object':
        objects.append((name, p)); return name
    if t == 'array': return '[' + typ(p['items'], name + 'Item') + ']'
    if t is None: t = 'boolean' if isinstance(p.get('const'), bool) else 'string'
    return {'string':'String','integer':'Int','number':'Double','boolean':'Bool'}[t]
for key, obj in defs.items(): objects.append((names[key], obj))
output = ['// Generated by fe/scripts/generate-models.py; contract artifacts are read-only.\nimport Foundation\n', '''private struct AnyKey: CodingKey {
    var stringValue: String
    var intValue: Int? { nil }
    init?(stringValue: String) { self.stringValue = stringValue }
    init?(intValue: Int) { return nil }
}
''']
i = 0
while i < len(objects):
    name, obj = objects[i]; i += 1
    props = [(k,typ(p,name+''.join(x.title() for x in k.split('_'))),p) for k,p in obj['properties'].items()]
    out = [f'public struct {name}: Codable, Equatable, Sendable {{']
    out += [f'    public var {k}: {t}' for k,t,p in props]
    out += ['    public init(' + ', '.join(f'{k}: {t}' + (' = []' if k == 'inference_history' else '') for k,t,p in props) + ') {']
    out += [f'        self.{k} = {k}' for k,t,p in props] + ['    }']
    out += ['    enum CodingKeys: String, CodingKey, CaseIterable {', '        case ' + ', '.join(k for k,t,p in props), '    }']
    out += ['    public init(from decoder: Decoder) throws {', '        let keys = try decoder.container(keyedBy: AnyKey.self)', '        let allowed = Set(CodingKeys.allCases.map(\\.rawValue))', '        guard Set(keys.allKeys.map(\\.stringValue)) == allowed else {', '            throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: "Unexpected or missing contract keys"))', '        }', '        let c = try decoder.container(keyedBy: CodingKeys.self)']
    if name == 'ExperienceV1':
        out = [line.replace(' == allowed else', '.isSubset(of: allowed), allowed.subtracting(["inference_history"]).isSubset(of: Set(keys.allKeys.map(\\.stringValue))) else') for line in out]
    for k,t,p in props:
        if k == 'inference_history':
            out.append('        inference_history = c.contains(.inference_history) ? try c.decode([ExperienceInferenceEntry].self, forKey: .inference_history) : []')
            continue
        optional = t.endswith('?')
        out.append(f'        {k} = try c.decode'+('IfPresent' if optional else '')+f'({t.rstrip("?")}.self, forKey: .{k})')
        q = next((x for x in p.get('anyOf',[]) if x.get('type') != 'null'),p)
        cond = None
        if 'enum' in q: cond = f'{json.dumps(q["enum"])}.contains(value)'
        elif 'const' in q: cond = f'value == {json.dumps(q["const"])}'
        elif q.get('type') == 'array' and 'enum' in q.get('items', {}):
            cond = f'value.allSatisfy({{ {json.dumps(q["items"]["enum"])}.contains($0) }})'
        if cond:
            guard = f'if let value = {k}' if optional else f'do {{ let value = {k};'
            if optional: guard += ' {'
            out += [f'        {guard}', f'            guard {cond} else {{ throw DecodingError.dataCorruptedError(forKey: .{k}, in: c, debugDescription: "Invalid contract value") }}', '        }']
    if name == 'Provenance':
        out += ['        guard (adapter == "plaid_sandbox") == (method == "transactions_sync"), adapter != "plaid_sandbox" || adapter_version == "1" else {', '            throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: "Invalid Sandbox provenance"))', '        }']
    if name == 'Observation':
        out += ['        if source_id == "plaid" {', '            guard mode == "fixture", kind == "purchase", time_precision == "date", occurred_at == nil, provenance.adapter == "plaid_sandbox", provenance.method == "transactions_sync" else {', '                throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: "Invalid Sandbox observation profile"))', '            }', '        } else if provenance.adapter == "plaid_sandbox" {', '            throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: "Sandbox provenance on another source"))', '        }']
    out += ['    }', '    public func encode(to encoder: Encoder) throws {', '        var c = encoder.container(keyedBy: CodingKeys.self)']
    out += [f'        try c.encode({k}, forKey: .{k})' for k,t,p in props] + ['    }','}\n']
    output.append('\n'.join(out))
(root/'fe/Core/Sources/CompanionCore/Contract.swift').write_text('\n'.join(output))
